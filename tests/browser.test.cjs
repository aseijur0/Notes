'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
// Optional local tooling; no dependency or browser downloads are needed by the app.
const playwrightPath = process.env.OSCP_PLAYWRIGHT || '/usr/lib/code-oss/resources/app/node_modules/playwright';
const {_electron} = require(playwrightPath);
const binary = process.env.OSCP_ELECTRON || '/usr/lib/code-oss/resources/app/node_modules/electron/dist/electron';
const xml = `<?xml version="1.0"?><!DOCTYPE nmaprun><nmaprun><host><status state="up"/><address addr="192.0.2.42" addrtype="ipv4"/><hostnames><hostname name="test.lab"/></hostnames><ports><port protocol="tcp" portid="80"><state state="open"/><service name="http" product="Apache" version="2.4"/><script id="http-title" output="&lt;img src=x onerror=alert(1)&gt;"/></port><port protocol="udp" portid="53"><state state="open|filtered"/><service name="domain"/></port><port protocol="tcp" portid="443"><state state="closed"/></port></ports><os><osmatch name="Linux"/></os><hostscript><script id="clock-skew" output="0s"/></hostscript></host><host><address addr="2001:db8::8" addrtype="ipv6"/><ports><port protocol="tcp" portid="22"><state state="open"/><service name="ssh" product="OpenSSH"/></port></ports></host></nmaprun>`;
(async () => {
  const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'oscp-map-browser-'));
  const env = {...process.env, OSCP_TEST_PROFILE: profile}; delete env.ELECTRON_RUN_AS_NODE;
  let app;
  try {
    app = await _electron.launch({executablePath: binary, args: ['--no-sandbox', path.join(__dirname, 'electron-main.cjs')], env, timeout: 20000});
    const page = await app.firstWindow(); await page.waitForSelector('#welcome');
    const errors = [], network = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('request', r => {if (/^https?:/.test(r.url())) network.push(r.url());});
    await page.setViewportSize({width: 1600, height: 1000});
    await page.screenshot({path: path.join(profile, 'welcome.png')});
    assert.equal(await page.locator('#welcome').isVisible(), true);
    assert.equal(await page.locator('#inspector').isVisible(), false);
    const expandedWidth = (await page.locator('#map-view').boundingBox()).width;
    await page.click('#workspace-toggle');
    assert.equal(await page.locator('#workspace-content').isVisible(), false);
    assert.equal(await page.locator('#workspace-toggle').getAttribute('aria-expanded'), 'false');
    assert.ok((await page.locator('#map-view').boundingBox()).width > expandedWidth);
    await page.click('#workspace-toggle');
    assert.equal(await page.locator('#workspace-content').isVisible(), true);
    await page.click('#demo-btn'); await page.waitForSelector('.graph-node');
    assert.equal(await page.locator('.graph-node').count(), 9);
    assert.equal(await page.locator('#workspace-content').isVisible(), false);
    assert.equal(await page.locator('#metrics').isVisible(), false);
    await page.screenshot({path: path.join(profile, 'map.png')});
    await page.locator('.graph-node').first().focus(); await page.keyboard.press('Enter');
    assert.equal(await page.locator('#inspector').isVisible(), true);
    const inspectingWidth = (await page.locator('#map-view').boundingBox()).width;
    await page.click('[data-close-inspector]');
    assert.equal(await page.locator('#inspector').isVisible(), false);
    assert.ok((await page.locator('#map-view').boundingBox()).width > inspectingWidth);
    await page.click('#workspace-toggle');
    await page.click('[data-view="credentials"]');
    assert.ok(!(await page.locator('#list-view').innerText()).includes('Example-only-password!'));
    await page.locator('#list-view [data-select]').first().click();
    await page.click('[data-reveal]'); assert.equal(await page.locator('#secret-value').innerText(), 'Example-only-password!');
    await page.click('[data-reveal]'); assert.ok(!(await page.locator('#secret-value').innerText()).includes('Example-only'));
    await page.click('[data-edit]'); await page.fill('[name="notes"]', 'Credential evidence updated'); await page.click('#submit-btn');
    assert.ok((await page.locator('#inspector').innerText()).includes('Credential evidence updated'));
    await page.click('#undo-btn');
    await page.click('#add-btn'); await page.fill('[name="username"]', 'new_user'); await page.fill('[name="secret"]', 'Do-not-display-this'); await page.click('#submit-btn');
    assert.equal(await page.locator('#count-credential').innerText(), '2');
    assert.ok(!(await page.locator('#list-view').innerText()).includes('Do-not-display-this'));
    await page.click('#add-btn'); await page.click('[data-form-kind="note"]');
    await page.fill('[name="title"]', '<img src=x onerror=alert(1)>'); await page.fill('[name="notes"]', 'Plain text <script>alert(1)</script>'); await page.click('#submit-btn');
    assert.equal(await page.locator('#inspector img, #inspector script').count(), 0);
    await page.click('[data-view="checklist"]'); const check = page.locator('#list-view [data-check-host]').last(); await check.check(); assert.equal(await check.isChecked(), true);
    await page.click('#link-btn'); await page.fill('[name="label"]', 'test relationship'); await page.click('#submit-btn');
    await page.click('[data-view="map"]'); assert.ok(await page.locator('[data-link]').count() >= 4);
    await page.fill('#search', 'WEB01'); assert.equal(await page.locator('.graph-node').count(), 1);
    await page.click('#clear-filters'); await page.click('#fit-btn');
    const graphNode = page.locator('.graph-node').first(), rect = await graphNode.boundingBox();
    await page.mouse.move(rect.x + 30, rect.y + 25); await page.mouse.down(); await page.mouse.move(rect.x + 90, rect.y + 70, {steps: 5}); await page.mouse.up();
    const downloadPromise = page.waitForEvent('download'); await page.click('#backup-btn'); const backup = await downloadPromise; const backupPath = path.join(profile, 'workspace.json'); await backup.saveAs(backupPath);
    const saved = JSON.parse(fs.readFileSync(backupPath, 'utf8')); assert.equal(saved.format, 'oscp-map'); assert.ok(Object.keys(saved.positions).length);
    await page.setInputFiles('#scan-input', {name: 'example.xml', mimeType: 'text/xml', buffer: Buffer.from(xml)});
    await page.waitForFunction(() => document.getElementById('dialog-title').textContent === 'Import results');
    assert.ok((await page.locator('#dialog-body').innerText()).includes('2 new hosts · 3 new services'));
    await page.click('#cancel-dialog');
    assert.equal(await page.locator('#workspace-content').isVisible(), false);
    assert.equal(await page.locator('#inspector').isVisible(), false);
    const importedMap = await page.locator('#map-view').boundingBox();
    assert.ok(importedMap.width > 1400 && importedMap.height > 700, 'Imported map should dominate the 1600 × 1000 viewport');
    await page.setInputFiles('#scan-input', {name: 'example.xml', mimeType: 'text/xml', buffer: Buffer.from(xml)});
    await page.waitForFunction(() => document.getElementById('dialog-body').textContent.includes('Already imported'));
    await page.click('#cancel-dialog');
    const xmlChecks = await page.evaluate(text => {
      const hosts = OSCP.parseXML(text); let rejects = 0;
      for (const invalid of ['<nmaprun><host></nmaprun>', '<html/>', '<!DOCTYPE nmaprun [<!ENTITY x "bad">]><nmaprun/>']) try {OSCP.parseXML(invalid);} catch {rejects++;}
      return {count: hosts.length, script: hosts[0].services[0].scripts, hostscript: hosts[0].notes, ipv6: hosts[1].address, rejects};
    }, xml);
    assert.equal(xmlChecks.count, 2); assert.match(xmlChecks.script, /<img/); assert.match(xmlChecks.hostscript, /clock-skew/); assert.equal(xmlChecks.ipv6, '2001:db8::8'); assert.equal(xmlChecks.rejects, 3);
    await page.setInputFiles('#backup-input', {name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"format":"wrong"}')});
    await page.waitForFunction(() => document.getElementById('dialog-title').textContent === 'Could not open backup'); await page.click('#cancel-dialog');
    await page.setInputFiles('#backup-input', backupPath); await page.waitForFunction(() => document.getElementById('dialog-title').textContent === 'Replace current workspace?'); await page.click('#submit-btn');
    assert.equal(await page.locator('#count-all').innerText(), String(saved.nodes.length));
    await page.click('#workspace-toggle');
    await page.click('#settings-btn'); await page.check('[name="autosave"]'); await page.click('#submit-btn');
    await page.reload(); await page.waitForSelector('.graph-node'); assert.equal(await page.locator('#count-all').innerText(), String(saved.nodes.length)); assert.match(await page.locator('#save-status').innerText(), /Restored/);
    await page.setViewportSize({width: 390, height: 844}); await page.screenshot({path: path.join(profile, 'mobile.png')});
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.click('#workspace-toggle');
    assert.equal(await page.locator('#workspace-content').isVisible(), true);
    await page.click('#workspace-toggle');
    assert.equal(await page.locator('#workspace-content').isVisible(), false);
    assert.deepEqual(errors, []); assert.deepEqual(network, []);
    console.log('Browser checks passed: file:// loading, graph, forms, masking, escaping, checklist, links, search, drag, XML, backup, autosave, mobile.');
    console.log('Screenshots: ' + profile);
  } finally {if (app) await app.close();}
})().catch(e => {console.error(e); process.exitCode = 1;});
